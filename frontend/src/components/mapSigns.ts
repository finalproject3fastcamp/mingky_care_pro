/**
 * 3D 지도 위에 뜨는 방 이름.
 *
 * 좌표는 **실측 모델 기준**(u, v)이라 지도 좌표가 아니다. 변환하지 않고 그대로
 * 3D 안의 자리로 쓴다(HospitalMap3D 에서 x=u, z=-v).
 *
 * 방 이름이 없으면 3D 는 그냥 흰 상자 더미다. 엔지니어가 "지금 로봇이 어느
 * 방 앞에 있나" 를 읽으려면 이름이 붙어 있어야 한다.
 *
 * 카운터 상판 자리는 3D 모형에서 뽑았고(윗면 0.21 m), 나머지는 해당 목적지를
 * 모델 좌표로 옮겨 잡았다.
 */

export interface Sign {
  label: string
  /** 둘째 줄. 없으면 한 줄이다 */
  sub?: string
  /** 실측 모델 좌표(m) */
  u: number
  v: number
  /** 놓이는 높이(m). 카운터 상판은 0.21 */
  y: number
  /** 주(1)·부(2) 위계. 2 는 작게 그린다 */
  rank: 1 | 2
}

